"""Write NEON_FONT into plugin.js: the capital letters of Tomorrow 400 as SVG paths.

    python3 scripts/neon-glyphs.py      (from the package root; needs fontTools)

A neon sign's word is drawn as paths, not text (plugin.js, dcNeonSigns): a
stroked text run prints as a Type 3 font, which the PDF/X build cannot keep
live and answers by flattening the whole page to an image. Paths stay vector,
take round-joined strokes for the tube's rings, and do not repeat the word four
times in the PDF's text. Coordinates are font units, y down, baseline at 0.
The block sits between its BEGIN and END lines in plugin.js (which imports
nothing at runtime)."""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
font = TTFont(ROOT / "fonts/tomorrow/tomorrow-400.ttf")
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
cap = font["OS/2"].sCapHeight

rows = []
for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ ":
    g = glyphs[cmap[ord(ch)]]
    pen = SVGPathPen(glyphs, ntos=lambda v: "%d" % round(v))
    g.draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
    rows.append(f"  {repr(ch)}: {{ w: {g.width}, d: '{pen.getCommands()}' }},")

BEGIN = "// BEGIN NEON_FONT (generated by scripts/neon-glyphs.py; do not edit)"
END = "// END NEON_FONT"
block = f"""{BEGIN}
// Tomorrow 400's capitals (SIL OFL, fonts/tomorrow/OFL.txt) as SVG paths:
// font units, y down, baseline at 0.
const NEON_FONT = {{
  upm: {upm},
  cap: {cap},
  glyphs: {{
{chr(10).join(rows)}
  }},
}};
{END}"""
plugin = ROOT / "plugin.js"
src = plugin.read_text()
i, j = src.index(BEGIN), src.index(END) + len(END)
plugin.write_text(src[:i] + block + src[j:])
print("wrote NEON_FONT into plugin.js:", upm, cap, len(block), "bytes")
